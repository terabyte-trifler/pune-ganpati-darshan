/**
 * Imports the Pune City Police's own visarjan geometry.
 *   npx tsx scripts/emit-police-geometry.mjs
 *
 * ---------------------------------------------------------------------
 * Why this replaces work that already worked.
 *
 * Everything drawn on /visarjan until now was derived: road centrelines
 * pulled from OSM by name, stretches trimmed by routing between junctions
 * we could find, a ring road approximated by asking OSRM to join five
 * points. Each step was checked, and each was still a reconstruction of
 * a plan the police had already published.
 *
 * diversion.punepolice.gov.in serves that plan directly. It is COARSER
 * than what we derived — Laxmi Road arrives as 47 points against the 112
 * we stitched from OSM — and that does not matter: the police are
 * authoritative about which stretch of road is shut, not about how
 * finely it is sampled, and a point every fifty metres draws the same
 * line on a phone.
 *
 * The two agree closely, which is the real reassurance: Laxmi Road 3.01
 * km against our 2.98, Tilak 2.06 against 2.08, their ring 18.53 km
 * against the 18.96 we routed through five guessed points.
 *
 * The gain is coverage. Six roads we could not place at all — Bajirao,
 * Ganesh, Shastri, FC, Karve, Deccan — are in their data.
 *
 * What is deliberately NOT imported:
 *
 *   - /TrackPalkhiApi/vehicleTrackings, the live positions. Tracking
 *     opens at 9am and the names are still placeholders ("." and "--"),
 *     so importing it now would draw forty-two dots called "." Live
 *     position stays a link to their tracker, which is right at the hour
 *     you read it in a way a cached copy never is.
 *   - The Palkhi leftovers in /appConfigs. This app is the Wari tracker
 *     repurposed, so it still carries "Loni Kalbhor & Saswad" and two
 *     Maharaj palkhi addresses. Nothing to do with visarjan.
 */
import { writeFileSync } from 'node:fs';

const BASE = 'https://diversion.punepolice.gov.in/TrackPalkhiApi';
const UA = 'Mozilla/5.0 (ganpatipune.in; public-service map)';

/** Their coordinates arrive as `{lat: 18.52, lng: 73.85},` — not JSON. */
function parseCoordinates(raw) {
  if (Array.isArray(raw)) {
    return raw
      .map((p) => [Number(p.lng ?? p.lon), Number(p.lat)])
      .filter(([x, y]) => Number.isFinite(x) && Number.isFinite(y));
  }
  const out = [];
  const re = /lat\s*:\s*(-?[\d.]+)\s*,\s*lng\s*:\s*(-?[\d.]+)/g;
  let m;
  while ((m = re.exec(String(raw))) !== null) {
    const lat = Number(m[1]);
    const lng = Number(m[2]);
    // Pune, generously. Anything outside is a parse artefact, not a road.
    if (lat > 18.3 && lat < 18.8 && lng > 73.6 && lng < 74.1) out.push([lng, lat]);
  }
  return out;
}

async function get(path) {
  const res = await fetch(`${BASE}/${path}`, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
}

const round = ([x, y]) => [Number(x.toFixed(6)), Number(y.toFixed(6))];

async function main() {
  console.log('fetching the police plan…');
  const [routes, icons] = await Promise.all([get('routes'), get('icons')]);

  const roads = [];
  for (const r of routes) {
    const path = parseCoordinates(r.coordinates).map(round);
    if (path.length < 2) {
      console.warn(`  SKIP  ${r.day} — ${path.length} usable points`);
      continue;
    }
    // Their ids arrive as strings ("5"), so coerce rather than widen the type.
    roads.push({ id: Number(r.id), road: String(r.day).trim(), kind: String(r.name).trim(), path });
    console.log(`  ${String(r.name).trim() === 'diversion' ? 'RING ' : 'ROAD '} ${String(r.day).trim().padEnd(16)} ${path.length} points`);
  }

  const parking = icons
    .filter((i) => String(i.icon_type).toUpperCase() === 'PARKING')
    .map((i) => ({
      name: String(i.popup_text ?? '').trim(),
      lat: Number(i.lat),
      lng: Number(i.lng),
    }))
    .filter((p) => p.name && Number.isFinite(p.lat) && Number.isFinite(p.lng));
  console.log(`  PARK  ${parking.length} designated parking places`);

  const body = `// GENERATED by scripts/emit-police-geometry.mjs — do not hand-edit.
//
// The Pune City Police's own visarjan plan, from
// diversion.punepolice.gov.in. Their order, their geometry: where this
// disagrees with anything we derived from OpenStreetMap, this wins.
//
// Live positions are NOT here and should not be added. They belong to
// the police tracker, which is right at the hour you read it; a copy
// taken at build time would not be.

export interface PoliceRoad {
  id: number;
  /** The road, as the police name it. */
  road: string;
  /** 'route' for a procession road, 'diversion' for the ring. */
  kind: string;
  /** [lng, lat] pairs. */
  path: [number, number][];
}

export const POLICE_ROADS: PoliceRoad[] = ${JSON.stringify(roads)};

export interface PoliceParking {
  name: string;
  lat: number;
  lng: number;
}

export const POLICE_PARKING: PoliceParking[] = ${JSON.stringify(parking, null, 2)};

export const POLICE_SOURCE = {
  authority: 'Pune City Police',
  url: 'https://diversion.punepolice.gov.in/',
  captured: '${new Date().toISOString().slice(0, 10)}',
};
`;
  writeFileSync(new URL('../src/content/visarjan-police.ts', import.meta.url), body);
  const pts = roads.reduce((n, r) => n + r.path.length, 0);
  console.log(`\nwrote ${roads.length} roads (${pts} points) and ${parking.length} parking places`);
}

main().catch((e) => {
  console.error(String(e.message ?? e));
  process.exit(1);
});
