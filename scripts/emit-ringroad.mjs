/**
 * The alternative ring road, as a closed loop.
 *   npx tsx scripts/emit-ringroad.mjs
 *
 * ---------------------------------------------------------------------
 * The check that matters.
 *
 * Every other line on this map describes something a reader should avoid.
 * This one is the opposite: it says "you can go this way", which is the
 * only instruction on the page capable of driving someone INTO a
 * barricade if it is wrong.
 *
 * So the routed loop is measured against the closures we draw, and the
 * script refuses to emit it if a meaningful stretch of it runs along a
 * road that is shut. Touching a closure at a single junction is expected
 * — Nal Stop is both a point on this ring and the end of the Karve Road
 * closure, which is precisely why it is a diversion point — but sharing
 * a carriageway is not.
 */
import { writeFileSync } from 'node:fs';
import { VISARJAN_GEOMETRY } from '../src/content/visarjan-geometry.ts';

const OSRM = 'https://router.project-osrm.org';
const UA = 'ganpatipune.in ringroad/1.0';

/** Metres: closer than this to a closed stretch counts as overlapping it. */
const OVERLAP_M = 60;
/** Refuse the route if more than this share of it overlaps a closure. */
const MAX_OVERLAP_SHARE = 0.08;

/**
 * The ring, in order, closing back on itself.
 *
 * Nal Stop is from the police's own closure map. The rest are OSM, and
 * each is a place with one obvious referent in Pune rather than a chowk
 * name that repeats across the district — the failure that once put
 * Tilak Chowk in Nigdi.
 */
const RING = [
  { name: 'Nal Stop', lat: 18.508591, lng: 73.831437, source: 'police closure map' },
  { name: 'Swargate', lat: 18.49975, lng: 73.85780, source: 'OSM' },
  { name: 'Golibar Maidan', lat: 18.50202, lng: 73.87742, source: 'OSM' },
  { name: 'RTO', lat: 18.52995, lng: 73.86327, source: 'OSM' },
  { name: 'Senapati Bapat Road', lat: 18.53193, lng: 73.82999, source: 'OSM' },
];

const R = 6371000;
const toRad = (d) => (d * Math.PI) / 180;
function haversine([x1, y1], [x2, y2]) {
  const dLat = toRad(y2 - y1);
  const dLng = toRad(x2 - x1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(y1)) * Math.cos(toRad(y2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

const closurePoints = VISARJAN_GEOMETRY.filter((g) => g.kind === 'closure')
  .flatMap((g) => g.segments.flat());

function nearestClosure(pt) {
  let best = Infinity;
  for (const c of closurePoints) best = Math.min(best, haversine(pt, c));
  return best;
}

async function main() {
  // Closing coordinate repeats the first, so OSRM returns a loop.
  const coords = [...RING, RING[0]].map((p) => `${p.lng},${p.lat}`).join(';');
  const url = `${OSRM}/route/v1/driving/${coords}?overview=full&geometries=geojson`;
  console.log('routing the ring…');
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  const json = await res.json();
  if (json.code !== 'Ok' || !json.routes?.length) {
    throw new Error(`OSRM declined: ${json.code} ${json.message ?? ''}`);
  }

  const line = json.routes[0].geometry.coordinates;
  const km = json.routes[0].distance / 1000;

  // Length-weighted overlap, so a long shared carriageway counts for more
  // than a single vertex that happens to sit near a closure.
  let total = 0;
  let overlapping = 0;
  for (let i = 1; i < line.length; i += 1) {
    const seg = haversine(line[i - 1], line[i]);
    total += seg;
    const mid = [(line[i - 1][0] + line[i][0]) / 2, (line[i - 1][1] + line[i][1]) / 2];
    if (nearestClosure(mid) < OVERLAP_M) overlapping += seg;
  }
  const share = total === 0 ? 0 : overlapping / total;

  console.log(`  loop length      : ${km.toFixed(2)} km, ${line.length} points`);
  console.log(`  runs along closures: ${Math.round(overlapping)} m (${(share * 100).toFixed(1)}%)`);

  if (share > MAX_OVERLAP_SHARE) {
    throw new Error(
      `the ring shares ${(share * 100).toFixed(1)}% of its length with a closed road — refusing to publish a route into a barricade`
    );
  }

  const body = `// GENERATED by scripts/emit-ringroad.mjs — do not hand-edit.
//
// Roads from OpenStreetMap via OSRM, © OpenStreetMap contributors, ODbL.
//
// The one line on this map that says "go", rather than "do not". It is
// checked against the closures before it is written: ${Math.round(overlapping)} m of its
// ${km.toFixed(2)} km runs within ${OVERLAP_M} m of a road we draw as shut, which is
// ${(share * 100).toFixed(1)}% and under the ${(MAX_OVERLAP_SHARE * 100).toFixed(0)}% the generator will allow. Nal Stop is
// deliberately among those metres: it is a point on this ring AND the end
// of the Karve Road closure, which is exactly why the police name it a
// diversion point.

export interface RingPoint {
  name: string;
  lat: number;
  lng: number;
  /** Where the coordinate came from, so a wrong one can be traced. */
  source: string;
}

export const RING_POINTS: RingPoint[] = ${JSON.stringify(RING, null, 2)};

/** [lng, lat] pairs, a closed loop. */
export const RING_PATH: [number, number][] = ${JSON.stringify(
    line.map(([x, y]) => [Number(x.toFixed(6)), Number(y.toFixed(6))])
  )};

export const RING_KM = ${km.toFixed(1)};
`;
  writeFileSync(new URL('../src/content/visarjan-ringroad.ts', import.meta.url), body);
  console.log(`wrote the ring: ${RING.length} points, ${km.toFixed(1)} km`);
}

main().catch((e) => {
  console.error(String(e.message ?? e));
  process.exit(1);
});
