/**
 * Closures the police tracker does not publish geometry for.
 *   npx tsx scripts/emit-extra-roads.mjs
 *
 * ---------------------------------------------------------------------
 * Why a second source at all.
 *
 * diversion.punepolice.gov.in carries eleven roads and the ring. The
 * traffic notice lists seventeen closures, so six of them have no line
 * on their map — and Jangli Maharaj Road is the one people ask about,
 * because it is the spine of Deccan.
 *
 * So it comes from OSM, and is only emitted when it can be tied back to
 * the notice. The notice says JM Road shuts from Jhansi Rani Chowk to
 * Khandoji Baba Chowk; the police junction map gives Khandoji Baba a
 * coordinate; the OSM road must reach it. It does, to within 7 m, which
 * is what makes drawing the whole named road honest rather than a guess
 * at where it starts and stops.
 *
 * OSM calls it "Jangli Maharaj Path". Matching on "Jangli Maharaj" alone
 * would also sweep in Jangli Maharaj Mandir, a temple half a kilometre
 * away, so the name is matched exactly.
 */
import { writeFileSync } from 'node:fs';
import { CLOSURE_JUNCTIONS } from '../src/content/diversions.ts';

const ENDPOINT = 'https://overpass-api.de/api/interpreter';
const UA = 'ganpatipune.in visarjan extra roads/1.0';

/** Each road, with the junction from the notice it has to reach. */
const WANTED = [
  {
    road: 'Jangli Maharaj Road',
    osmName: 'Jangli Maharaj Path',
    anchor: 'Khandojibaba Chowk',
    /** Metres. Beyond this it is not the road the notice means. */
    tolerance: 120,
  },
];

const R = 6371000;
const toRad = (d) => (d * Math.PI) / 180;
function haversine([x1, y1], [x2, y2]) {
  const dLat = toRad(y2 - y1);
  const dLng = toRad(x2 - x1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(y1)) * Math.cos(toRad(y2)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}

async function overpass(query, attempt = 1) {
  const res = await fetch(ENDPOINT, {
    method: 'POST',
    headers: { 'User-Agent': UA, 'Content-Type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({ data: query }),
  });
  const text = await res.text();
  if (!text.trimStart().startsWith('{')) {
    if (attempt >= 6) throw new Error(`Overpass refused after ${attempt} tries`);
    await new Promise((r) => setTimeout(r, 8000 * attempt));
    return overpass(query, attempt + 1);
  }
  return JSON.parse(text);
}

const round = ([x, y]) => [Number(x.toFixed(6)), Number(y.toFixed(6))];

async function main() {
  const out = [];

  for (const w of WANTED) {
    const query = `[out:json][timeout:60];way["highway"]["name"="${w.osmName}"](18.48,73.80,18.56,73.90);out geom;`;
    console.log(`fetching ${w.osmName}…`);
    const data = await overpass(query);

    const segments = data.elements
      .filter((e) => e.geometry?.length >= 2)
      .map((e) => e.geometry.map((p) => round([p.lon, p.lat])));

    if (segments.length === 0) {
      console.warn(`  MISS   ${w.road}`);
      continue;
    }

    const junction = CLOSURE_JUNCTIONS.find((j) => j.name === w.anchor);
    if (!junction) throw new Error(`no coordinate for ${w.anchor}`);
    const anchor = [junction.lng, junction.lat];

    const points = segments.flat();
    const reach = Math.round(Math.min(...points.map((p) => haversine(anchor, p))));

    if (reach > w.tolerance) {
      console.warn(`  REJECT ${w.road} — nearest point is ${reach} m from ${w.anchor}`);
      continue;
    }

    const length =
      segments.reduce(
        (sum, s) => sum + s.slice(1).reduce((t, p, i) => t + haversine(s[i], p), 0),
        0
      ) / 1000;

    console.log(
      `  DRAW   ${w.road} — ${segments.length} segments, ${points.length} points, ` +
        `${length.toFixed(2)} km, reaches ${w.anchor} to ${reach} m`
    );
    out.push({ road: w.road, osmName: w.osmName, anchor: w.anchor, reachM: reach, segments });
  }

  const body = `// GENERATED by scripts/emit-extra-roads.mjs — do not hand-edit.
//
// Road geometry from OpenStreetMap, © OpenStreetMap contributors, ODbL.
//
// Closures the police tracker publishes no line for. Each is emitted
// only when the OSM road reaches the junction the notice names, so the
// extent drawn is the extent ordered rather than whatever shares a name.

export interface ExtraRoad {
  /** The notice's spelling, so it matches VISARJAN_CLOSURES. */
  road: string;
  /** What OSM calls it, kept so a wrong match can be spotted. */
  osmName: string;
  /** The junction from the notice this was checked against. */
  anchor: string;
  /** How close the road gets to that junction, in metres. */
  reachM: number;
  segments: [number, number][][];
}

export const EXTRA_ROADS: ExtraRoad[] = ${JSON.stringify(out)};
`;
  writeFileSync(new URL('../src/content/visarjan-extra-roads.ts', import.meta.url), body);
  console.log(`\nwrote ${out.length} road(s)`);
}

main().catch((e) => {
  console.error(String(e.message ?? e));
  process.exit(1);
});
